/**
 * SPEC 63 DP — dialect variants of the demonstrative pronouns (тамтой, отой, оцей, тот/тота/тото, сесь), research/32.
 *
 * > "Як той відмінюється отой, тамтой, як цей – оцей та сей." — Синявський, Норми, розд. 5 (research/32 §2.6)
 * > "вказівного займенника тамто́й «той»" — uk.wikipedia, Наддністрянський говір, «Граматика і словотвір» (research/32 §2.5)
 * > "тамтой (тамтому) - той (тому)" — Лемківський Словничок (research/32 §2.4)
 *
 * A variant is DATA: one operation on the paradigm of its standard lemma (VESUM lines, verbatim tags) + the sources that attest it.
 * Forms are generated by rule from the standard paradigm; there is no hand-written form list. `scope` says how far a source describes
 * the variant: 'full' (the source says it declines like the standard lemma) or 'nominative' (the source gives nominative forms only —
 * oblique cases are unknown and are NOT derived). `cells` are forms given verbatim by a source for a cell (they replace the rule output there).
 * The dialect group of every attestation comes from the AC gazetteer (core/autolabel.ts, region → group) or, when the source is itself an article
 * about one говір, from that named говір; a region the gazetteer does not know gives no group (P-3.1).
 */
import { Q, type Evidence } from './evidence.ts'
import { gazEvidence, gazetteerRows } from './autolabel.ts'

export interface StdEntry { form: string; tags: string }
export interface VariantAttest { ev: Evidence; /** region name exactly as the source states it → gazetteer */ region?: string; /** dialect code when the source is an article about that говір */ named?: string; note?: string }
export type VariantOp = { kind: 'prefix'; p: string } | { kind: 'stem'; from: string; to: string }
export interface VariantCell { /** tag substring of the standard cell, e.g. 'adj:m:v_naz' */ match: string; forms: string[]; ev: Evidence; /** true = in addition to the rule output of the cell (a second ending); false/absent = replaces it */ extra?: boolean }
export interface PronounVariant {
  id: string; std: string; op: VariantOp; scope: 'full' | 'nominative'; scopeEv: Evidence
  /** the standard forms the sources describe (others are not derived); absent = all in scope */
  only?: string[]; cells?: VariantCell[]; attest: VariantAttest[]
}

