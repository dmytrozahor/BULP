export const variantById = (id: string) => PRONOUN_VARIANTS.find(v => v.id === id)
export const variantsOfStd = (std: string) => PRONOUN_VARIANTS.filter(v => v.std === std)

export interface VariantForm { form: string; tags: string; variant: string; std: string; stdForm: string; rule: string; sourced: boolean }
/** DP-2: the paradigm of one variant, generated from the standard lemma's paradigm; every output carries the tags of the standard cell it comes from. */
export function deriveVariant(v: PronounVariant, std: StdEntry[]): VariantForm[] {
  const out = new Map<string, VariantForm>()
  const put = (f: VariantForm) => { const k = f.form + '|' + f.tags; if (!out.has(k)) out.set(k, f) }
  for (const e of std) {
    const cell = v.cells?.find(c => !c.extra && e.tags.includes(c.match) && !/:long\b/.test(e.tags))
    if (cell) { for (const form of cell.forms) put({ form, tags: e.tags, variant: v.id, std: v.std, stdForm: e.form, rule: `${v.id}:cell`, sourced: true }); continue }
    if (v.scope === 'nominative' && !e.tags.includes(':v_naz')) continue
    if (v.only && !v.only.includes(e.form)) continue
    const form = v.op.kind === 'prefix' ? v.op.p + e.form : e.form.startsWith(v.op.from) ? v.op.to + e.form.slice(v.op.from.length) : undefined
    if (form) put({ form, tags: e.tags, variant: v.id, std: v.std, stdForm: e.form, rule: v.op.kind === 'prefix' ? `${v.id}:prefix-${v.op.p}` : `${v.id}:stem-${v.op.from}>${v.op.to}`, sourced: false })
  }
  // cells given by a source that the standard paradigm does not enumerate as a separate line (extra neuter ending): тото next to тоте
  for (const c of v.cells ?? []) for (const e of std.filter(x => x.tags.includes(c.match) && !/:long\b/.test(x.tags))) for (const form of c.forms) put({ form, tags: e.tags, variant: v.id, std: v.std, stdForm: e.form, rule: `${v.id}:cell`, sourced: true })
  return [...out.values()]
}

/** DP-3: the dialect claims of a variant — one per attestation, group from the gazetteer (region) or the named говір; none when neither knows it. */
export interface VariantClaim { code?: string; region?: string; evidence: Evidence[]; note?: string }
export function variantClaims(v: PronounVariant): VariantClaim[] {
  return v.attest.map(a => {
    const rows = a.region ? gazetteerRows(a.region) : []
    const code = rows[0]?.group ?? a.named
    return { code, region: a.region, evidence: [a.ev, ...rows.slice(0, 1).map(gazEvidence)], note: a.note }
  })
}
export const variantGroups = (v: PronounVariant) => [...new Set(variantClaims(v).flatMap(c => (c.code ? [c.code] : [])))]
/** every derived variant form of a standard lemma, with the variant it belongs to */
export const deriveAll = (std: string, paradigm: StdEntry[]) => variantsOfStd(std).flatMap(v => deriveVariant(v, paradigm))
