/**
 * SPEC 63 YT-1/YT-2 — dated evidence of the ѣ merger: spelling interchanges per witness and century (output: analysis/yat-interchange.md).
 * Method (no etymological gold exists in the corpus; the lexeme lists are hand-picked, so counts are LOWER-BOUND samples, not rates):
 *  A. YAT lexemes (etymological ѣ, template with Y): count the token spelled with ѣ / и / і / е at the Y position.
 *  B. NON-YAT lexemes (etymological е or и, template with Y): count tokens spelled with ѣ at the Y position (ѣ written for е/и — hypercorrection).
 * Tokens are lower-cased, stripped of combining marks / apostrophes, Latin i → і, ы → и. Whole-token match.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const YAT: [string, string][] = [   // [lexeme label, regex; Y = the vowel position]
  ['дѣти', '^дYт(?:и|ей|ям|ьми|ях|ки|ок|ина|ині)$'], ['хлѣб', '^хлYб(?:ъ|а|у|ом|е|ы|и|ов|)$'], ['мѣсто', '^мYст(?:о|а|у|ом|ѣ|е|ъ|ы|и)$'],
  ['мѣсяць', '^мYся(?:ць|ца|цу|цем|цѣ|ц|цъ)$'], ['гдѣ', '^гдY$'], ['нигдѣ', '^нигдY$'], ['вѣра', '^вYр(?:а|ы|у|ою|ѣ|и)$'],
  ['человѣкъ', '^(?:чо|че)ловYк(?:ъ|а|у|ом|ѣ|и|)$'], ['сѣно', '^сYн(?:о|а|у|ом|ѣ)$'], ['лѣс', '^лYс(?:ъ|а|у|ом|ѣ|ы|и|)$'],
  ['цѣлый', '^цYл(?:ый|ий|ая|ое|ого|ой|ую|ым|ыи)$'], ['свѣтъ', '^свYт(?:ъ|а|у|ом|ѣ|ы|и|)$'], ['дѣло', '^дYл(?:о|а|у|ом|ѣ|ы|и|ъ)$'],
  ['всѣ', '^всY(?:х|м|ми|хъ|мъ)$'], ['тѣло', '^тYл(?:о|а|у|ом|ѣ|ы|ъ)$'], ['рѣка', '^рYк(?:а|и|у|ою|ѣ|ы)$'], ['пѣсня', '^пYсн(?:я|и|ю|ѣ|е)$'],
]
const NONYAT: [string, string][] = [
  ['жена', '^жYн(?:а|ы|у|ою|ѣ|и)$'], ['земля', '^зYмл(?:я|ѣ|и|ю|ею|ей)$'], ['вечеръ', '^вYчер(?:ъ|а|у|ом|ѣ|ы|и|)$'], ['весна', '^вYсн(?:а|ы|у|ою|ѣ|и)$'],
  ['писати', '^пYса(?:ти|ть|ль|в)$'], ['письмо', '^пYсьм(?:о|а|у|ом|ѣ)$'],
]
const norm = (s: string) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ·’'`ʼ]/g, '').normalize('NFC').replace(/[iı]/g, 'і').replace(/ы/g, 'и')
const mk = (src: string) => new RegExp(src.replace('Y', '([ѣиіе])'))
type Cnt = Record<string, number>
const cent = (y: number) => Math.floor((y - 1) / 100) + 1
interface Row { yat: Cnt; non: Cnt }
const byC = new Map<number, Row>(), byW = new Map<string, Row & { c: number; d: [number, number] }>()
const row = (): Row => ({ yat: {}, non: {} })
const bump = (o: Cnt, k: string) => { o[k] = (o[k] ?? 0) + 1 }
const YR = YAT.map(([, s]) => mk(s)), NR = NONYAT.map(([, s]) => mk(s))
for (const f of readdirSync('data/work')) {
  if (!f.endsWith('.json') || f.includes('.nlp')) continue
  let j: any; try { j = JSON.parse(readFileSync('data/work/' + f, 'utf8')) } catch { continue }
  if (!Array.isArray(j.tokens) || !Array.isArray(j.date)) continue
  const mid = Math.round((j.date[0] + j.date[1]) / 2); if (mid > 1850 || mid < 900) continue
  const C = cent(mid), rc = byC.get(C) ?? (byC.set(C, row()), byC.get(C)!)
  const wk = String(j.unit ?? j.id).replace(/_\d+.*$/, '').replace(/\d+$/, '') + ':' + C
  const rw = byW.get(wk) ?? (byW.set(wk, { ...row(), c: C, d: j.date }), byW.get(wk)!)
  for (const t of j.tokens) {
    if (!t.raw) continue
    const w = norm(String(t.raw))
    for (const re of YR) { const m = re.exec(w); if (m) { bump(rc.yat, m[1]!); bump(rw.yat, m[1]!) } }
    for (const re of NR) { const m = re.exec(w); if (m) { bump(rc.non, m[1]!); bump(rw.non, m[1]!) } }
  }
}
const g = (o: Cnt, k: string) => o[k] ?? 0
const sum = (o: Cnt) => Object.values(o).reduce((a, b) => a + b, 0)
const pct = (a: number, b: number) => (b ? (100 * a / b).toFixed(0) + '%' : '—')
const Cs = [...byC.keys()].sort((a, b) => a - b)
let md = `# ѣ ↔ и/і/е interchange in the corpus (SPEC 63 YT-1/YT-2)\n\nGenerated by \`pipelines/yat-interchange.ts\` from data/work/*.json (witnesses dated ≤ 1850). **Lower-bound sample**: hand-picked lexemes (script header), whole-token match; и/і/е counts may include homographs (дити, лито…). Century = midpoint of the witness date range.\n\n`
md += `## A. Etymological ѣ lexemes: how the ѣ position is spelled\n\n| Century | tokens | ѣ | и | і | е | ѣ kept |\n|---|---|---|---|---|---|---|\n`
for (const C of Cs) { const r = byC.get(C)!, n = sum(r.yat); if (n) md += `| ${C} | ${n} | ${g(r.yat, 'ѣ')} | ${g(r.yat, 'и')} | ${g(r.yat, 'і')} | ${g(r.yat, 'е')} | ${pct(g(r.yat, 'ѣ'), n)} |\n` }
md += `\n## B. Etymological е/и/і lexemes (жена, земля, вечеръ, весна, писати, письмо): how that position is spelled\n\n| Century | tokens | ѣ (hypercorrect) | е/и/і | ѣ share |\n|---|---|---|---|---|\n`
for (const C of Cs) { const r = byC.get(C)!, n = sum(r.non); if (n) md += `| ${C} | ${n} | ${g(r.non, 'ѣ')} | ${n - g(r.non, 'ѣ')} | ${pct(g(r.non, 'ѣ'), n)} |\n` }
md += `\n## C. Per witness group and century (groups with ≥ 8 tokens; B ѣ = ѣ written for е/и/і)\n\n| Witness group:century | dates | A n | ѣ | и | і | е | B n | B ѣ |\n|---|---|---|---|---|---|---|---|---|\n`
for (const [k, r] of [...byW.entries()].sort((a, b) => a[1].c - b[1].c || a[0].localeCompare(b[0]))) {
  const n = sum(r.yat), nb = sum(r.non); if (n + nb < 8) continue
  md += `| ${k} | ${r.d[0]}–${r.d[1]} | ${n} | ${g(r.yat, 'ѣ')} | ${g(r.yat, 'и')} | ${g(r.yat, 'і')} | ${g(r.yat, 'е')} | ${nb} | ${g(r.non, 'ѣ')} |\n`
}
writeFileSync('analysis/yat-interchange.md', md)
console.log(md.split('\n').slice(0, 40).join('\n'))
