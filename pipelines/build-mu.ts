/**
 * BUILD stage, SPEC 63 MU-3: capitalised unresolved tokens of Middle Ukrainian witnesses (modern letters) become name cards (/name/:id, basis «capitalisation»),
 * and analysis/middle-ukr-extraction.md reports link % before/after per witness with the rule counts and the reasons the rest stays unlinked.
 * A name card says nothing but «capitalised mid-paragraph, no VESUM form, never written with a small letter in the corpus» (type and modern form: unknown, SPEC 00).
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import type { WitnessOut } from '../core/types.ts'
import { TorotScan, torotId, type NameCard } from '../core/torot.ts'
import { MU_FOLDS, MU_ORTH, muCandidates } from '../core/mu-fold.ts'
import { key } from '../core/text.ts'

type W = Pick<WitnessOut, 'id' | 'title' | 'tokens' | 'orth' | 'lang'>
const CAP = /^\p{Lu}[\p{Ll}'’ʼ-]{2,}$/u

/** Name cards for unresolved capitalised tokens; `refs` = 'n:<id>' per token (same shape as TorotScan refs). */
export function capNames(ws: { w: W; ids: Int32Array }[], taken: ReadonlySet<string>): { names: NameCard[]; refs: Map<string, string[]>; tokens: Map<string, number> } {
  const lower = new Set<string>()
  for (const { w } of ws) for (const t of w.tokens) if (t.raw !== t.raw.toUpperCase() && t.raw[0] === t.raw[0]!.toLowerCase()) lower.add(t.raw.normalize('NFC').toLowerCase())
  const scan = new TorotScan(), refs = new Map<string, string[]>(), tokens = new Map<string, number>()
  for (const { w, ids } of ws) {
    if (!w.orth || !MU_ORTH.has(w.orth)) continue
    const r: string[] = []; let any = false, n = 0
    w.tokens.forEach((t, i) => {
      const lo = t.raw.normalize('NFC').toLowerCase(), first = i === 0 || w.tokens[i - 1]!.s !== t.s
      if (ids[i]! >= 0 || first || !CAP.test(t.raw) || lower.has(lo) || taken.has(torotId(lo))) { r.push(''); return }
      r.push(scan.add('name', w.id, { raw: t.raw, lemma: lo, morph: 'Ne', loc: t.loc }) ?? ''); any = true; n++
    })
    if (any) { refs.set(w.id, r); tokens.set(w.id, n) }
  }
  const names = scan.file('').names.map(c => ({ ...c, pos: 'власна назва (велика літера)', morph: '', basis: 'capitalisation' as const }))
  return { names, refs, tokens }
}

export interface MuWitness { w: W; n: number; linked: number; names: number; rules: Record<string, number>; unresolved: Map<string, number> }
const pct = (a: number, n: number) => (n ? (100 * a / n).toFixed(1) : '0.0') + '%'

export function muReport(rows: MuWitness[], before: Record<string, { n: number; linked: number }>, outDir: string, focus: string[]): string {
  let md = '# Middle Ukrainian extraction (SPEC 63 MU-3)\n\nGenerated by `pipelines/build-mu.ts`. Witnesses whose text is Middle Ukrainian in modern letters (orth «modernised» / «ізборник-нормалізований»). ' +
    '«before» = tokens linked by the build without the MU folds (`analysis/mu-baseline.json`); «after» = linked by the same stage with the MU folds of `core/mu-fold.ts` (each rule cited there and in research/35); ' +
    '«names» = unresolved capitalised tokens that got a name card (capitalisation only; type and modern form unknown).\n\n' +
    '| witness | tokens | before | after (VESUM link) | gained | names (cap.) | link + names |\n|---|---|---|---|---|---|---|\n'
  let tn = 0, tb = 0, ta = 0, tm = 0
  for (const r of rows) {
    const b = before[r.w.id]?.linked ?? 0; tn += r.n; tb += b; ta += r.linked; tm += r.names
    md += `| ${r.w.id} — ${r.w.title.slice(0, 48)} | ${r.n} | ${b} (${pct(b, r.n)}) | ${r.linked} (${pct(r.linked, r.n)}) | +${r.linked - b} | ${r.names} | ${pct(r.linked + r.names, r.n)} |\n`
  }
  md += `| **all ${rows.length}** | ${tn} | ${tb} (${pct(tb, tn)}) | ${ta} (${pct(ta, tn)}) | +${ta - tb} | ${tm} | ${pct(ta + tm, tn)} |\n`
  const rules: Record<string, number> = {}
  for (const r of rows) for (const [k, v] of Object.entries(r.rules)) rules[k] = (rules[k] ?? 0) + v
  md += '\n## Rules that fired (tokens linked through the rule; a token may pass two rules, e.g. enclitic split + past -л → -в)\n\n| rule | tokens | source |\n|---|---|---|\n'
  for (const f of MU_FOLDS) if (rules[f.id]) md += `| ${f.id} | ${rules[f.id]} | ${f.cite.source} ${f.cite.locator.split(' (')[0]} |\n`
  md += '\nA candidate is accepted only if VESUM lists it with the analysis the rule states (e.g. MU-FEM-OJ-GEN: adjective/pronoun, fem., genitive); the token\'s own POS gate applies where an annotation exists. Rules without a citable description are not implemented (research/35 §4).\n'
  for (const id of focus) {
    const r = rows.find(x => x.w.id === id); if (!r) continue
    md += `\n## ${id} — ${r.w.title}: remaining unlinked (top 40)\n\nReason codes: **MU-no-vesum** = at least one MU rule changes the word but no candidate is a VESUM form with the stated analysis; **no-rule** = no cited MU rule applies (typically a Russian/Church Slavonic lexical form or an irregular stem, for which no dictionary mapping is cited).\n\n| token | n | reason |\n|---|---|---|\n`
    for (const [t, n] of [...r.unresolved].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 40)) md += `| ${t} | ${n} | ${muCandidates(key(t)).length ? 'MU-no-vesum' : 'no-rule'} |\n`
  }
  writeFileSync(resolve(outDir, 'middle-ukr-extraction.md'), md)
  return md
}
