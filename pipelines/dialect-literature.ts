/**
 * SPEC 63 CX-9 report → analysis/dialect-literature.md: per dialect-literature witness (those with `dialect` statements in the manifest and their narration controls)
 * tokens, a link proxy, and which dialect rules (DIALECT_RULES incl. DIALECT_BOOK_RULES and DIALECT_LEX_RULES) fire, per group — a validation of the rules against real dialect text.
 * Standalone (does not rebuild public/data): reads data/work/<id>.json written by `tsx pipelines/ingest.ts <unit>`.
 * Link proxy = token whose spelling (or one of its orthography folds) is a VESUM form; the real linking (build-link.ts) additionally uses rules/lemmatisation, so the final link % is higher.
 * Rule context mirrors build-annotate cardCtx: form = key(raw), vesum = analyses of the modern form (first fold candidate that is in VESUM, else the spelling), year = witness date.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { MANIFEST } from './manifest.ts'
import { vesumIndex } from './vesum.ts'
import { fold } from '../core/orthography.ts'
import { key } from '../core/text.ts'
import { DIALECTS, DIALECT_RULES } from '../core/rules.ts'
import type { Ctx, VesumHit } from '../core/detect.ts'
import type { WitnessOut } from '../core/types.ts'

const units = MANIFEST.filter(u => u.dialect?.length)
const ids = units.flatMap(u => u.split === 'dialogue' ? [`${u.id}_dlg`, `${u.id}_nar`] : [u.id])
const ws = ids.filter(id => existsSync(`data/work/${id}.json`)).map(id => JSON.parse(readFileSync(`data/work/${id}.json`, 'utf8')) as WitnessOut)
const unitOf = (w: WitnessOut) => units.find(u => u.id === w.unit)!

const candsOf = (raw: string, orth?: string) => [...new Set(fold(key(raw), orth).map(c => key(c.form)))]
const forms = new Set<string>()
for (const w of ws) for (const t of w.tokens) for (const c of candsOf(t.raw, w.orth)) forms.add(c)
const dry = new Set<string>()
const ctxOf = (w: WitnessOut, raw: string, hits: Map<string, VesumHit[]> | null): Ctx => {
  const cs = candsOf(raw, w.orth), form = key(raw)
  const modern = hits ? cs.find(c => hits.has(c)) ?? form : form
  return { form, norm: cs[0], year: w.date[1], vesum: hits?.get(modern) ?? [], inLexicon: k => { const kk = key(k); if (!hits) { dry.add(kk); return [] } return hits.get(kk) ?? [] } }
}
for (const w of ws) for (const t of w.tokens) for (const r of DIALECT_RULES) r.test(ctxOf(w, t.raw, null))   // dry run: which VESUM keys do the rules ask for?
const idx = await vesumIndex(new Set([...forms, ...dry]), new Set())

const pct = (a: number, b: number) => b ? (100 * a / b).toFixed(1) + ' %' : '–'
const out: string[] = []
const ruleGroups = new Map<string, string[]>()
for (const r of DIALECT_RULES) ruleGroups.set(r.label, [...(ruleGroups.get(r.label) ?? []), r.id])
const stat = ws.map(w => {
  const byForm = new Map<string, number>()
  for (const t of w.tokens) byForm.set(t.raw, (byForm.get(t.raw) ?? 0) + 1)
  let linked = 0
  const fired = new Map<string, number>()      // rule id → tokens
  const examples = new Map<string, Map<string, number>>()
  for (const [raw, n] of byForm) {
    if (candsOf(raw, w.orth).some(c => idx.hits.has(c))) linked += n
    const c = ctxOf(w, raw, idx.hits)
    for (const r of DIALECT_RULES) if (r.test(c)) {
      fired.set(r.id, (fired.get(r.id) ?? 0) + n)
      const m = examples.get(r.id) ?? new Map(); m.set(raw.toLowerCase(), (m.get(raw.toLowerCase()) ?? 0) + n); examples.set(r.id, m)
    }
  }
  return { w, types: byForm.size, linked, fired, examples }
})

out.push('# Dialect literature (SPEC 63 CX-9)', '',
  'Generated by `tsx pipelines/dialect-literature.ts` from `data/work/*.json` (not a rebuild of `public/data`). Link % here is a **proxy** (spelling or orthography fold is a VESUM form); the build\'s link % is higher (rules, lemmatisation).',
  'Rule firing = `DIALECT_RULES` (+ book + lexical rows) evaluated on each distinct spelling with the build\'s context (rules fire only on non-normative forms); counts are tokens. Details of sources and rejected items: research/40.', '')
out.push('## Witnesses', '', '| witness | tokens | types | VESUM proxy link | rules fired (rows) | tokens with a dialect rule | sourced group | user hypothesis |', '|---|---|---|---|---|---|---|---|')
for (const s of stat) {
  const u = unitOf(s.w), sourced = u.dialect!.filter(d => d.status === 'sourced').map(d => d.group), hy = u.dialect!.filter(d => d.status === 'hypothesis').map(d => d.group)
  const isNar = s.w.id.endsWith('_nar')
  const tok = new Set<string>(); for (const [id] of s.fired) tok.add(id)
  const anyTokens = (() => { let n = 0; const seen = new Map<string, boolean>(); for (const t of s.w.tokens) { let f = seen.get(t.raw); if (f === undefined) { f = [...s.fired.keys()].some(id => s.examples.get(id)?.has(t.raw.toLowerCase())); seen.set(t.raw, f) } if (f) n++ } return n })()
  out.push(`| \`${s.w.id}\` | ${s.w.tokens.length} | ${s.types} | ${pct(s.linked, s.w.tokens.length)} | ${s.fired.size} | ${anyTokens} (${pct(anyTokens, s.w.tokens.length)}) | ${isNar ? '— (narration, control)' : sourced.join(', ') || 'none'} | ${isNar ? '—' : hy.join(', ')} |`)
}
out.push('')
for (const s of stat) {
  out.push(`## ${s.w.id}`, '', `${s.w.title}. ${s.w.edition}`, '')
  const u = unitOf(s.w)
  if (!s.w.id.endsWith('_nar')) for (const d of u.dialect ?? []) out.push(`- ${d.status === 'sourced' ? '**sourced label**' : 'hypothesis (not a label)'} ${d.group}${d.author ? ` — ${d.author}, ${d.date}` : ''}: ${d.evidence.map(e => `«${e.quote}» (${e.locator})`).join('; ')}`)
  out.push('', '| group | rows fired | tokens | top rules (id: tokens; examples) |', '|---|---|---|---|')
  const byGroup = new Map<string, { rows: string[]; tokens: number }>()
  for (const [id, n] of s.fired) { const g = id.split(':').pop()!, label = DIALECT_RULES.find(r => r.id === id)!.label; const e = byGroup.get(label) ?? { rows: [], tokens: 0 }; e.rows.push(id); e.tokens += n; byGroup.set(label, e); void g }
  for (const [g, e] of [...byGroup].sort((a, b) => b[1].tokens - a[1].tokens)) {
    const top = e.rows.sort((a, b) => s.fired.get(b)! - s.fired.get(a)!).slice(0, 4).map(id => `${id}: ${s.fired.get(id)}; ${[...s.examples.get(id)!].sort((a, b) => b[1] - a[1]).slice(0, 3).map(x => x[0]).join(', ')}`).join(' / ')
    out.push(`| ${g} ${DIALECTS[g] ?? ''} | ${e.rows.length} | ${e.tokens} | ${top} |`)
  }
  const own = u.dialect!.filter(d => d.status === 'sourced').map(d => d.group)
  if (!s.w.id.endsWith('_nar') && own.length) for (const g of own) {
    const rows = ruleGroups.get(g) ?? [], dead = rows.filter(id => !s.fired.has(id))
    out.push('', `Rules of the group ${g} (${rows.length} rows) that fired: ${rows.length - dead.length}; **never fired on this ${g} text: ${dead.length}**${dead.length ? ' — ' + dead.slice(0, 60).join(', ') + (dead.length > 60 ? ' …' : '') : ''}`)
  }
  const hy = u.dialect!.filter(d => d.status === 'hypothesis').map(d => d.group)
  if (!s.w.id.endsWith('_nar') && hy.length && !u.dialect!.some(d => d.status === 'sourced' && hy.includes(d.group))) {
    const g = hy[0]!, rows = ruleGroups.get(g) ?? [], f = rows.filter(id => s.fired.has(id))
    out.push('', `Rules of the user's hypothesised group ${g} (not a label): ${f.length}/${rows.length} rows fire${f.length ? ' — ' + f.slice(0, 20).map(id => `${id}: ${s.fired.get(id)}`).join(', ') : ''}`)
  }
  out.push('')
}
writeFileSync('analysis/dialect-literature.md', out.join('\n'))
console.log(out.slice(0, 16).join('\n'))
