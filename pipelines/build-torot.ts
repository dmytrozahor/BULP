/**
 * BUILD stage, SPEC 63 PV-1…PV-5: classify every token of every TOROT witness (token carries a TOROT lemma) as linked / name / ORV-only,
 * write public/data/torot.json (name cards + ORV-only cards) and the `ref` column of the text shards, and analysis/torot-extraction.md.
 * The strict VESUM link (build-link.ts) is untouched: a TOROT lemma is evidence, the modern lemma still needs a VESUM-attested fold/derivation candidate.
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import type { WitnessOut } from '../core/types.ts'
import { bucketOf, TorotScan, type Bucket, type TorotFile } from '../core/torot.ts'

export interface TorotIn {
  w: Pick<WitnessOut, 'id' | 'title' | 'tokens' | 'lang'>
  ids: Int32Array                        // lemma index per token (-1 = not linked)
  reasonOf: (ti: number) => string       // why a token with a TOROT lemma did not link (gate / no VESUM form …)
  lemmaOf: (idx: number) => { display: string; tags: string }
  model?: boolean                        // PV-8: lemma/morph are Stanza ORV output
}
export interface TorotWitnessStat { id: string; title: string; n: number; withLemma: number; linked: number; names: number; orv: number; none: number; topOrv: { lemma: string; n: number; reason: string; ex: string }[]; reasons: Record<string, number> }

export function scanTorot(ins: TorotIn[], generated: string): { file: TorotFile; refs: Map<string, string[]>; stats: TorotWitnessStat[] } {
  const scan = new TorotScan(), refs = new Map<string, string[]>(), stats: TorotWitnessStat[] = []
  for (const { w, ids, reasonOf, lemmaOf, model } of ins) {
    const st: TorotWitnessStat = { id: w.id, title: w.title + (model ? " [Stanza ORV, модель]" : ""), n: w.tokens.length, withLemma: 0, linked: 0, names: 0, orv: 0, none: 0, topOrv: [], reasons: {} }
    const r: string[] = [], per = new Map<string, { n: number; reason: string; ex: string }>()
    w.tokens.forEach((t, ti) => {
      const linked = ids[ti]! >= 0, b: Bucket = bucketOf(t, linked)
      if (t.lemma) st.withLemma++
      st[b === 'linked' ? 'linked' : b === 'name' ? 'names' : b === 'orv' ? 'orv' : 'none']++
      const reason = b === 'orv' ? reasonOf(ti) : undefined
      const L = linked ? lemmaOf(ids[ti]!) : undefined
      const ref = scan.add(b, w.id, t, { model, reason, modern: L && /:prop\b/.test(':' + L.tags) ? L.display : undefined })
      r.push(ref ?? (b === 'linked' && L ? 'w:' + L.display : ''))
      if (b === 'orv' && reason) { st.reasons[reason] = (st.reasons[reason] ?? 0) + 1; const p = per.get(t.lemma!) ?? per.set(t.lemma!, { n: 0, reason, ex: `${t.raw} @${t.loc}` }).get(t.lemma!)!; p.n++ }
    })
    st.topOrv = [...per].sort((a, b) => b[1].n - a[1].n || a[0].localeCompare(b[0])).slice(0, 50).map(([lemma, v]) => ({ lemma, ...v }))
    refs.set(w.id, r); stats.push(st)
  }
  return { file: scan.file(generated), refs, stats }
}

// ── PV-6: light cards for lemmas that KEEP_MIN_F dropped ─────────────────────────────────────────
/** `lemmas[i]` = [lemma, VESUM lemma tags, token count, example «witness|citation|spelling»]; the card shows exactly this (VESUM status + this token's KWIC locator). */
export interface LightFile { generated: string; source: string; lemmas: [string, string, number, string][] }
export function lightIndex(ws: Pick<WitnessOut, 'id' | 'tokens'>[], ids: Int32Array[], lemmaList: { display: string; tags: string; f: number }[], keep: Uint8Array): { file: LightFile; refs: Map<string, string[]> } {
  const refs = new Map<string, string[]>(), ex = new Map<number, string>()
  ws.forEach((w, wi) => {
    const r: string[] = []; let any = false
    w.tokens.forEach((t, ti) => {
      const i = ids[wi]![ti]!
      if (i < 0 || keep[i]) { r.push(''); return }
      r.push('l:' + lemmaList[i]!.display); any = true
      if (!ex.has(i)) ex.set(i, `${w.id}|${t.loc}|${t.raw}`)
    })
    if (any) refs.set(w.id, r)
  })
  const lemmas = [...ex].map(([i, e]): [string, string, number, string] => [lemmaList[i]!.display, lemmaList[i]!.tags, lemmaList[i]!.f, e])
  return { file: { generated: new Date().toISOString(), source: 'VESUM dict_corp_vis.txt v6.8.6 (lemma tags); example = first linked token of the lemma in an admitted witness', lemmas }, refs }
}

const pct = (a: number, n: number) => (n ? (100 * a / n).toFixed(1) : '0.0') + '%'
/** analysis/torot-extraction.md; `before` = strict VESUM link counts of the previous build (public/data/corpus.json before this stage existed). */
export function torotReport(stats: TorotWitnessStat[], before: Record<string, number>, outDir: string, extra: { id: string; n: number; linked: number; what: string }[] = []): string {
  let md = '# TOROT extraction (SPEC 63 PV-4)\n\nGenerated by `pipelines/build-torot.ts`. Source: TOROT treebank (CC BY-NC-SA 3.0), per-token `lemma`, `part-of-speech`, `morphology`, `citation-part`. ' +
    '«before» = tokens linked to a modern VESUM lemma by the previous build; «after» = linked + proper names (POS Ne → /name/:id) + ORV-only lemma cards (/orv/:id). ' +
    'The strict VESUM link is a separate column and is not loosened: a TOROT lemma is evidence, the modern lemma needs a VESUM-attested fold/derivation candidate. TOROT lav.xml carries no abbreviation-expansion attribute and no gloss, so neither is claimed (gloss: unknown).\n\n' +
    '| witness | tokens | with TOROT lemma | linked before | linked now (VESUM, Ne tokens counted as names) | names (Ne) | ORV-only | no TOROT lemma, unlinked | covered after |\n|---|---|---|---|---|---|---|---|---|\n'
  for (const s of stats) {
    const b = before[s.id]
    md += `| ${s.id} | ${s.n} | ${s.withLemma} | ${b === undefined ? 'n/a' : `${b} (${pct(b, s.n)})`} | ${s.linked + 0} (${pct(s.linked, s.n)}) | ${s.names} | ${s.orv} | ${s.none} | ${pct(s.linked + s.names + s.orv, s.n)} |\n`
  }
  md += '\n## PV-6 / PV-7 witnesses (strict VESUM link, before → after)\n\n| witness | what | tokens | before | after |\n|---|---|---|---|---|\n'
  for (const e of extra) { const b = before[e.id]; md += `| ${e.id} | ${e.what} | ${e.n} | ${b === undefined ? 'n/a' : `${b} (${pct(b, e.n)})`} | ${e.linked} (${pct(e.linked, e.n)}) |\n` }
  md += '\nPV-6: lemmas dropped by KEEP_MIN_F get a light card (/lw/:lemma, public/data/light.json), so text pages link them although the strict link count is unchanged. PV-7: titlo expansion (core/text.ts TITLO + NOMINA_BARE) feeds derive(); VESUM must still list the result.\n'
  for (const s of stats) {
    md += `\n##${s.id} — ${s.title}\n\nReasons an ORV-only lemma has no modern link: ${Object.entries(s.reasons).map(([k, v]) => `${k}: ${v}`).join('; ') || 'none'}.\n\nTop-50 remaining unlinked lemmas (TOROT lemma, tokens, reason, first example @ citation-part):\n\n| lemma | n | reason | example |\n|---|---|---|---|\n`
    for (const o of s.topOrv) md += `| ${o.lemma} | ${o.n} | ${o.reason} | ${o.ex} |\n`
  }
  writeFileSync(resolve(outDir, 'torot-extraction.md'), md)
  return md
}
